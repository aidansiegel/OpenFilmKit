"""Write packaging/requirements-brew.txt: exact versions and hashes of the Python packages the
Homebrew formula installs, so every install gets the same files.

Uses the exact versions OpenFilmKit's tests and conversion checks ran on (PACKAGES), after
checking each has wheels for every platform the formula supports (macOS arm64 and x86_64, Linux
x86_64 and aarch64) on the formula's Python; a package pinned to None gets its newest such
release. Records the SHA-256 of every file in the release; pip installs with --require-hashes.
OpenCV stays on 4.x: 5.0 reorganized modules, including the face detector `clean` uses.

Usage: python3 tools/pin_python_deps.py
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

PACKAGES = {'numpy': '2.4.2', 'pillow': '12.0.0', 'opencv-python-headless': '4.14.0.94',
            'setuptools': None}
PYTHON = '314'   # the formula's python@3.14
PLATFORMS = {'macOS arm64': r'macosx_\d+_\d+_(arm64|universal2)',
             'macOS x86_64': r'macosx_\d+_\d+_(x86_64|universal2)',
             'Linux x86_64': r'(many|musl)?linux.*_x86_64',
             'Linux aarch64': r'(many|musl)?linux.*_aarch64'}
OUT = Path(__file__).resolve().parents[1] / 'packaging' / 'requirements-brew.txt'


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'openfilmkit-pin/1.0'})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def version_key(v):
    return tuple(int(x) for x in re.findall(r'\d+', v)[:4])


def fits(files):
    """True when every platform has a wheel this Python can use (or the package is pure Python)."""
    wheels = [f['filename'] for f in files if f['filename'].endswith('.whl') and not f.get('yanked')]
    if any(w.endswith('-none-any.whl') for w in wheels):
        return True
    usable = [w for w in wheels if re.search(rf'-cp{PYTHON}-|-cp3\d+-abi3-', w)]
    return all(any(re.search(p, w) for w in usable) for p in PLATFORMS.values())


def pin(name, exact=None):
    data = fetch(f'https://pypi.org/pypi/{name}/json')
    if exact:
        files = data['releases'].get(exact)
        if not files or not fits(files):
            sys.exit(f'{name}=={exact}: missing, or lacks wheels for every platform on cp{PYTHON}')
        return exact, sorted(f['digests']['sha256'] for f in files if not f.get('yanked'))
    for version in sorted(data['releases'], key=version_key, reverse=True):
        if re.search(r'[a-zA-Z]', version):      # skip pre-releases
            continue
        files = data['releases'][version]
        if files and fits(files):
            return version, sorted(f['digests']['sha256'] for f in files if not f.get('yanked'))
    sys.exit(f'{name}: no release with wheels for every platform on cp{PYTHON}')


def main():
    lines = ['# Generated by tools/pin_python_deps.py; installed with pip --require-hashes.',
             f'# Python 3.{PYTHON[1:]}; wheels for: {", ".join(PLATFORMS)}.']
    for name, exact in PACKAGES.items():
        version, hashes = pin(name, exact)
        lines.append(f'{name}=={version} \\')
        lines += [f'    --hash=sha256:{h} \\' for h in hashes[:-1]] + [f'    --hash=sha256:{hashes[-1]}']
        print(f'{name}=={version} ({len(hashes)} files)')
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
